"""Run reference / do-nothing / stop-early over MCP on seeds 1-10 and write docs/results.md.

Each run starts a fresh server process (one episode per process), plays the policy through the MCP
tools, then scores it through the token-gated verifier route, exactly like the Harbor verifier.

    uv run python scripts/baselines.py [--seeds 1-10]
"""

from __future__ import annotations

import argparse
import json
import os
import socket
import statistics
import subprocess
import sys
import time
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "solution"))

from reference import run  # noqa: E402

TOKEN = "baselines-token"
POLICIES = ["reference", "do-nothing", "stop-early"]


def free_port():
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    p = s.getsockname()[1]
    s.close()
    return p


def play(seed: int, policy: str, level: int = 1):
    port = free_port()
    env = dict(os.environ, GSS_SEED=str(seed), GSS_LEVEL=str(level), GSS_VERIFIER_TOKEN=TOKEN, GSS_PORT=str(port), GSS_HOST="127.0.0.1")
    proc = subprocess.Popen([sys.executable, "-m", "server.app"], cwd=ROOT, env=env,
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        for _ in range(200):
            try:
                socket.create_connection(("127.0.0.1", port), timeout=0.2).close()
                break
            except OSError:
                time.sleep(0.1)
        notes = run(f"http://127.0.0.1:{port}/mcp", policy)

        def get(path):
            req = urllib.request.Request(f"http://127.0.0.1:{port}{path}",
                                         headers={"Authorization": f"Bearer {TOKEN}"})
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.loads(r.read())

        return get("/verifier/result"), get("/verifier/trajectory")["trajectory"], notes
    finally:
        proc.terminate()
        proc.wait(5)


def fmt_dt(v):
    return "–" if v is None else (f"{v:.1f}" if v < 1e4 else f"{v:.2e}")


def recipe(seed, res, traj):
    lines = [f"# Expert lab recipe (seed {seed}, level {res.get('level', 1)})", "",
             "By-product of the reference run: what the scripted expert did, in order, with lab time.", "",
             f"- OPA wavelength {res['opa_lambda_nm']:.0f} nm. Parts bought: DL-C25 delay stage, 4 x MIR-1 mirror, "
             f"1 x PER-1 periscope, {', '.join(res['diagnostics_bought'])} "
             f"(EUR {res['cost_eur']:.0f}; C_min = EUR {res['c_min_eur']:.0f})",
             f"- Lab time: {res['lab_time_min']:.1f} min of 240 ({100 * res['lab_time_frac']:.1f}%), "
             f"{res['tool_calls']} tool calls",
             f"- Result: eta = {res['eta']:.4f}, R = {res['reward']:.4f}, O = {res['O']:.4f}, "
             f"|dt| = {fmt_dt(res['abs_dt_fs'])} fs", "",
             "| # | t (min) | tool | args |", "|---|---|---|---|"]
    for s in traj:
        args = json.dumps(s["args"])
        lines.append(f"| {s['i']} | {s['t_s'] / 60:.1f} | {s['tool']} | `{args}` |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", default="1-10")
    ap.add_argument("--level", type=int, default=1, choices=(1, 2))
    a = ap.parse_args()
    lo, _, hi = a.seeds.partition("-")
    seeds = list(range(int(lo), int(hi or lo) + 1))
    rows = {p: [] for p in POLICIES}
    for seed in seeds:
        for p in POLICIES:
            res, traj, _ = play(seed, p, a.level)
            rows[p].append(res)
            print(seed, p, {k: res[k] for k in ("reward", "eta", "lab_time_frac", "tool_calls")}, flush=True)
            if p == "reference" and seed == seeds[0]:
                sfx = "" if a.level == 1 else f"_l{a.level}"
                with open(os.path.join(ROOT, "docs", f"expert_recipe_seed{seed}{sfx}.md"), "w") as f:
                    f.write(recipe(seed, res, traj))

    out = [f"# Baseline results, level {a.level}", "",
           f"Generated by `uv run python scripts/baselines.py --level {a.level}`: every run is a fresh MCP server process, "
           "played through the MCP tools and scored through the token-gated verifier route.", "",
           "Pass criteria: reference eta >= 0.9 and <= 65% of the 4 h budget on every seed; "
           "do-nothing and stop-early R < 0.05 on every seed.", ""]
    out += ["| policy | seed | OPA nm | R | eta | O | abs dt (fs) | cost (EUR) | C_min (EUR) | lab time | tool calls |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for p in POLICIES:
        for seed, r in zip(seeds, rows[p]):
            out.append(f"| {p} | {seed} | {r['opa_lambda_nm']:.0f} | {r['reward']:.4f} | {r['eta']:.4f} | {r['O']:.4f} | "
                       f"{fmt_dt(r['abs_dt_fs'])} | {r['cost_eur']:.0f} | {r['c_min_eur']:.0f} | "
                       f"{100 * r['lab_time_frac']:.1f}% | "
                       f"{r['tool_calls']} |")
    out += ["", "## Summary", "", "| policy | mean R | min R | max R | max lab time | pass |", "|---|---|---|---|---|---|"]
    for p in POLICIES:
        R = [r["reward"] for r in rows[p]]
        tmax = max(r["lab_time_frac"] for r in rows[p])
        if p == "reference":
            ok = all(r["eta"] >= 0.9 and r["lab_time_frac"] <= 0.65 for r in rows[p])
        else:
            ok = all(x < 0.05 for x in R)
        out.append(f"| {p} | {statistics.fmean(R):.4f} | {min(R):.4f} | {max(R):.4f} | {100 * tmax:.1f}% | "
                   f"{'yes' if ok else 'NO'} |")
    with open(os.path.join(ROOT, "docs", "results.md" if a.level == 1 else f"results_l{a.level}.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out[-5:]))


if __name__ == "__main__":
    main()
